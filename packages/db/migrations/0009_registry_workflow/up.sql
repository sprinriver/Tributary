-- Cells exactly as uploaded, so publish re-validates against the pinned template and diffs are exact.
alter table sample add column raw jsonb not null default '{}';
-- Stable manifest order (created_at ties within a transaction; uuidv7 is not monotonic within a millisecond).
alter table sample add column position bigint generated by default as identity;
alter table experiment_version add column is_latest_published boolean not null default false;
create unique index experiment_version_one_latest on experiment_version (experiment_id) where is_latest_published;

-- Same guard as 0005, now also letting the latest-published flag move on published versions.
create or replace function guard_experiment_version() returns trigger language plpgsql as $$
declare
  ignored text[] := array['status', 'updated_at', 'search_tsv', 'embedding', 'is_latest_published'];
begin
  if old.status = 'draft' then
    return case when tg_op = 'DELETE' then old else new end;
  end if;
  if tg_op = 'DELETE' then
    raise exception 'experiment_version % is %, and published versions are immutable', old.id, old.status
      using errcode = 'TR409';
  end if;
  if (to_jsonb(new) - ignored) is distinct from (to_jsonb(old) - ignored)
     or (old.status = 'archived' and new.status <> 'archived')
     or (old.status = 'published' and new.status not in ('published', 'archived')) then
    raise exception 'experiment_version % is %; create a new version instead', old.id, old.status
      using errcode = 'TR409';
  end if;
  return new;
end
$$;

-- Exactly one latest-published version per experiment: the highest published version number.
-- Clear first, then set, so the partial unique index never sees two flagged rows.
create function refresh_latest_published(experiment uuid) returns void language plpgsql as $$
declare latest uuid;
begin
  select id into latest from experiment_version
  where experiment_id = experiment and status = 'published' and deleted_at is null
  order by version_number desc limit 1;
  update experiment_version set is_latest_published = false
  where experiment_id = experiment and is_latest_published and id is distinct from latest;
  if latest is not null then
    update experiment_version set is_latest_published = true where id = latest and not is_latest_published;
  end if;
end
$$;

create function maintain_latest_published() returns trigger language plpgsql as $$
begin
  perform refresh_latest_published(new.experiment_id);
  return null;
end
$$;
create trigger maintain_latest_published after insert or update of status, deleted_at on experiment_version
  for each row execute function maintain_latest_published();

do $$
declare e uuid;
begin
  for e in select distinct experiment_id from experiment_version loop
    perform refresh_latest_published(e);
  end loop;
end
$$;
